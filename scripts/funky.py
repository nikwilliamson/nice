#!/usr/bin/env python3
"""Funky scenes from ha/funky.json: writes ha/packages/nice_funky.yaml (the scenes) and
ha/custom_templates/nice/funky_list.jinja (what the Funky card offers). Run, then
scripts/deploy.sh rules.

In each room the colour lights take the scene's colours in turn, starting one further along
in each room, so neighbouring lights and rooms differ. Every other light is a little dimmer."""
import colorsys, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = json.loads((ROOT / "ha/funky.json").read_text())


def hs(hex_):
    r, g, b = (int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5))
    hh, ss, _ = colorsys.rgb_to_hsv(r, g, b)
    return [round(hh * 360, 1), round(ss * 100, 1)]


def q(s):
    return json.dumps(s)


out = ["# Generated by scripts/funky.py from ha/funky.json. Edit that and run it again.",
       "# Funky scenes: colourful, whole house; white-only lights off. The Funky card on the",
       "# Home grid turns them on through script.activate_lighting_scene (Adaptive Lighting",
       "# paused for their lights).", "scene:"]
for sc in spec["scenes"]:
    cols = [hs(c) for c in sc["colors"]]
    out += [f"- id: funky_{sc['id']}", f"  name: {q('Funky - ' + sc['name'])}", "  icon: mdi:party-popper", "  entities:"]
    for r, (room, lights) in enumerate(spec["color_lights"].items()):
        for i, light in enumerate(lights):
            h, s = cols[(i + r) % len(cols)]
            bri = sc["brightness"] if i % 2 == 0 else round(sc["brightness"] * 0.75)
            out.append(f"    {light}: {{state: 'on', hs_color: [{h}, {s}], brightness: {bri}}}")
    for light in spec["white_lights_off"]:
        out.append(f"    {light}: {{state: 'off'}}")
    st = spec["strip"]
    out.append(f"    {st['light']}: {{state: 'on', effect: {q(sc['fx'])}, brightness: {sc['brightness']}}}")
    out.append(f"    {st['palette']}: {{state: {q(sc['palette'])}}}")
(ROOT / "ha/packages/nice_funky.yaml").write_text("\n".join(out) + "\n")

card = [dict(id=f"scene.funky_{sc['id']}", name=sc["name"], colors=sc["colors"]) for sc in spec["scenes"]]
(ROOT / "ha/custom_templates/nice/funky_list.jinja").write_text(
    "{#- Generated by scripts/funky.py from ha/funky.json: the funky scenes the card offers. -#}\n"
    "{%- macro funky_scenes() -%}" + json.dumps(card) + "{%- endmacro -%}\n")
n = sum(len(v) for v in spec["color_lights"].values())
print(f"{len(spec['scenes'])} scenes: {n} colour lights, {len(spec['white_lights_off'])} white lights off, 1 strip")
